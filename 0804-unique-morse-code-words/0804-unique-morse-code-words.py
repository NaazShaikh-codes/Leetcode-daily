class Solution:
    def uniqueMorseRepresentations(self, words: list[str]) -> int:
        morse_code = {
            "a": ".-",
            "b": "-...",
            "c": "-.-.",
            "d": "-..",
            "e": ".",
            "f": "..-.",
            "g": "--.",
            "h": "....",
            "i": "..",
            "j": ".---",
            "k": "-.-",
            "l": ".-..",
            "m": "--",
            "n": "-.",
            "o": "---",
            "p": ".--.",
            "q": "--.-",
            "r": ".-.",
            "s": "...",
            "t": "-",
            "u": "..-",
            "v": "...-",
            "w": ".--",
            "x": "-..-",
            "y": "-.--",
            "z": "--.."
        }
        unique_code = set()
        for word in words:
            transformed = ""
            for letter in word:
                transformed += morse_code[letter]
            unique_code.add(transformed)
        return len(unique_code)